"""Generate APFS Unicode mapping tables from Python's Unicode database."""

import sys
import unicodedata

EXPECTED_UNICODE_VERSION = "15.0.0"


def mappings():
    decompositions = []
    decomposition_values = []
    casefolds = []
    casefold_values = []
    combining = []

    for codepoint in range(0x110000):
        char = chr(codepoint)
        decomposition = unicodedata.decomposition(char)
        if decomposition and not decomposition.startswith("<"):
            values = [int(value, 16) for value in decomposition.split()]
            decompositions.append((codepoint, len(decomposition_values),
                                   len(values)))
            decomposition_values.extend(values)

        folded = char.casefold()
        if folded != char:
            values = [ord(value) for value in folded]
            casefolds.append((codepoint, len(casefold_values), len(values)))
            casefold_values.extend(values)

        ccc = unicodedata.combining(char)
        if ccc:
            combining.append((codepoint, ccc))

    max_expansion = max(
        len(unicodedata.normalize(
            "NFD",
            unicodedata.normalize("NFD", chr(codepoint)).casefold()))
        for codepoint in range(0x110000)
    )
    if max_expansion > 12:
        sys.exit("Unicode transform expansion exceeds implementation bound")

    return decompositions, decomposition_values, casefolds, casefold_values, combining


def emit_values(out, name, values):
    out.write(f"static const uint32_t {name}[] = {{\n")
    for start in range(0, len(values), 8):
        out.write("\t" + ", ".join(f"0x{x:x}" for x in values[start:start + 8]))
        out.write(",\n")
    out.write("};\n\n")


def emit_mappings(out, name, values):
    out.write(f"static const struct apfs_unicode_mapping {name}[] = {{\n")
    for codepoint, offset, length in values:
        out.write(f"\t{{ 0x{codepoint:x}, {offset}, {length} }},\n")
    out.write("};\n\n")


def main():
    if unicodedata.unidata_version != EXPECTED_UNICODE_VERSION:
        sys.exit("expected Unicode " + EXPECTED_UNICODE_VERSION + ", got " +
                 unicodedata.unidata_version)

    (decomposition, decomposition_values, casefold, casefold_values,
     combining) = mappings()
